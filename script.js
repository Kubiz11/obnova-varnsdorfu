const programCards = document.querySelectorAll(".program-card");

const programDetail = document.getElementById("programDetail");
const programClose = document.getElementById("programClose");

const detailLetter = document.getElementById("detailLetter");
const detailTitle = document.getElementById("detailTitle");
const detailSubtitle = document.getElementById("detailSubtitle");
const detailList = document.getElementById("detailList");
const detailEnding = document.getElementById("detailEnding");


programCards.forEach(card => {

    card.addEventListener("click", () => {

        const programName = card.dataset.program;
        const data = programData[programName];

        if (!data) return;

        detailLetter.textContent = data.letter;
        detailTitle.textContent = data.title;
        detailSubtitle.textContent = data.subtitle;
        detailEnding.textContent = data.ending;

        detailList.innerHTML = "";

        data.points.forEach(point => {

            const li = document.createElement("li");

            li.textContent = point;

            detailList.appendChild(li);

        });

        programDetail.classList.add("active");

       setTimeout(() => {
    const headerHeight = document.querySelector(".header").offsetHeight;
    const detailTop =
        programDetail.getBoundingClientRect().top +
        window.scrollY;

    window.scrollTo({
        top: detailTop - headerHeight - 20,
        behavior: "smooth"
    });
}, 300);

    });

});


programClose.addEventListener("click", () => {

    programDetail.classList.remove("active");

});
let lastScrollY = window.scrollY;
const header = document.querySelector(".header");

window.addEventListener("scroll", () => {
    const currentScrollY = window.scrollY;

    if (currentScrollY > lastScrollY && currentScrollY > 100) {
        // Scroll dolů → schovat
        header.classList.add("header-hidden");
    } else {
        // Scroll nahoru → zobrazit
        header.classList.remove("header-hidden");
    }

    lastScrollY = currentScrollY;
});
const menuButton = document.getElementById("menuButton");
const navigation = document.querySelector(".navigation");

menuButton.addEventListener("click", () => {
    navigation.classList.toggle("active");
});

navigation.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
        navigation.classList.remove("active");
    });
});
const backToTop = document.getElementById("backToTop");

window.addEventListener("scroll", () => {
    if (window.scrollY > 500) {
        backToTop.classList.add("show");
    } else {
        backToTop.classList.remove("show");
    }
});

backToTop.addEventListener("click", () => {
    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
});